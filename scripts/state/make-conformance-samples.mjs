#!/usr/bin/env node
// Writes apps/web/src/pages/conformanceSamples.ts from the golden files (Phase 3, Prompt 7).
//
//   node scripts/state/make-conformance-samples.mjs
//
// The /conformance page shows these counts and 12 sample rows; it computes "CarePlan Scheduler says"
// live with calculate3c. `differences` is this script's own count of golden rows that a plain
// re-statement of the 3c's formulas gets wrong; apps/web/test/conformance.test.ts replays the golden
// file with the engine and fails unless it is 0 and this module matches the golden file.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const STATE = join(ROOT, "docs", "fixtures", "state");
const OUT = join(ROOT, "apps", "web", "src", "pages", "conformanceSamples.ts");

const FACTOR = { 1: 5, 2: 10, 3: 15, 4: 19, 5: 23, 6: 27, 7: 31 };
/** The task rows to show, as [Min/Day, Days/Wk] on the CDS tab. */
export const TASK_SAMPLES = [[309, 5], [61, 7], [45, 3], [1, 1], [1440, 7], [15, 7], [7, 3], [10, 2], [100, 6], [600, 4]];

const sha256 = (file) => createHash("sha256").update(readFileSync(join(STATE, file))).digest("hex");

export function build() {
  const c = JSON.parse(readFileSync(join(STATE, "hcbs3c-golden.json"), "utf8"));
  const a = JSON.parse(readFileSync(join(STATE, "hcbs3a-golden.json"), "utf8"));
  let differences = 0;
  for (const w of c.workbooks) {
    let total = Math.floor((w.inputs.transportMinutes ?? 0) / 15);
    if (total !== w.transportUnits) differences++;
    for (const [row, [min, days]] of Object.entries(w.inputs.rows)) {
      const units = days === null ? null : Math.floor(((min ?? 0) * FACTOR[days] + 14) / 15);
      if (units !== w.units[row]) differences++;
      total += units ?? 0;
    }
    if (total !== w.totalUnits) differences++;
  }
  const cds = c.workbooks.filter((w) => w.tab === "CDS");
  const samples = TASK_SAMPLES.map(([min, days]) => {
    const w = cds.find((x) => Object.values(x.inputs.rows).some(([l, n]) => l === min && n === days));
    const row = Object.keys(w.inputs.rows).find((r) => w.inputs.rows[r][0] === min && w.inputs.rows[r][1] === days);
    return { kind: "task", tab: "CDS", minPerDay: min, daysPerWeek: days, transportMinutes: null, recorded: w.units[row] };
  });
  const ceiling = c.meta.tabs.CDS.ceilingValue;
  for (const total of [ceiling, ceiling + 1]) {
    const w = cds.find((x) => x.totalUnits === total && Object.keys(x.inputs.rows).length === 1 && x.inputs.transportMinutes !== null);
    const [[min, days]] = Object.values(w.inputs.rows);
    samples.push({ kind: "total", tab: "CDS", minPerDay: min, daysPerWeek: days, transportMinutes: w.inputs.transportMinutes, recorded: w.totalUnits });
  }
  const tabCounts = Object.fromEntries(["CDS", "ILW"].map((tab) => [tab, c.meta.caseCounts[tab]]));
  return {
    generated: c.meta.generated,
    libreOffice: c.meta.soffice,
    differences,
    hcbs3c: {
      file: "4.00appendix4da-3cform.xlsx", sha256: sha256("4.00appendix4da-3cform.xlsx"), sourceSha256: c.meta.sourceSha256,
      editions: { CDS: c.meta.tabs.CDS.edition, ILW: c.meta.tabs.ILW.edition },
      ceilings: { CDS: c.meta.tabs.CDS.ceilingValue, ILW: c.meta.tabs.ILW.ceilingValue },
      workbooks: c.meta.caseCounts.workbooks, tabs: tabCounts,
      minutes: c.meta.minutesRange, days: c.meta.daysRange,
    },
    hcbs3a: {
      file: "4.00appendix3da3aform.xlsx", sha256: sha256("4.00appendix3da3aform.xlsx"), sourceSha256: a.meta.sourceSha256,
      edition: a.meta.edition, workbooks: a.meta.caseCounts.workbooks, taskRows: a.meta.caseCounts.taskRows,
      libreOffice: a.meta.soffice,
    },
    samples,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const data = build();
  writeFileSync(OUT, [
    "// Generated by scripts/state/make-conformance-samples.mjs from docs/fixtures/state/hcbs3c-golden.json and",
    "// hcbs3a-golden.json. Do not edit; run the script again. apps/web/test/conformance.test.ts checks it.",
    "",
    `export const CONFORMANCE = ${JSON.stringify(data, null, 2)} as const;`,
    "",
  ].join("\n"));
  console.log(`wrote ${OUT}: ${data.samples.length} samples, ${data.differences} differences`);
}
